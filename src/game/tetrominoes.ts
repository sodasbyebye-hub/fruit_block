export function getPieceCells(piece: Tetromino): Point[] {
  const rotations = SHAPES[piece.type];
  return rotations[piece.rotation % rotations.length].map((cell) => ({
    x: piece.x + cell.x,
    y: piece.y + cell.y,
  }));
}
